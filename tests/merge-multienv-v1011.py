#!/usr/bin/env python3
"""Merge disjoint v10.11 batches with strict seed and branch accounting."""
import argparse,csv,json,pathlib,statistics
ROOT=pathlib.Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--batches',type=pathlib.Path,default=ROOT/'evidence/v1011_batches');p.add_argument('--out',type=pathlib.Path,default=ROOT/'evidence/v1011_multienv');p.add_argument('--seeds',type=int,default=6);o=p.parse_args();o.out.mkdir(parents=True,exist_ok=True)
records={k:[] for k in ('branches','trajectories','checkpoint_hashes')}
folders=sorted(o.batches.glob('part*'));assert folders,'No batch directories'
for folder in folders:
 for name in records:
  with (folder/(name+'.csv')).open(newline='',encoding='utf8') as f:records[name].extend(csv.DictReader(f))
 # Validate every batch was generated by the same scientific protocol
 meta=json.loads((folder/'summary.json').read_text());assert meta['horizon_tick']==2200 and meta['checkpoint_tick']==300
seeds=list(range(13101,13101+o.seeds));hash_by={int(x['seed']):x['checkpoint_sha256'] for x in records['checkpoint_hashes']}
assert len(hash_by)==len(records['checkpoint_hashes'])==o.seeds and sorted(hash_by)==seeds
conditions=('reference','scarce','abundant','migration_cost','isolated_regions')
branch_keys={(int(x['seed']),x['scenario'],x['branch']) for x in records['branches']}
assert len(branch_keys)==len(records['branches'])==o.seeds*11
for seed in seeds:
 for c in conditions:
  for b in ('control','prune_root')+ (('function_root_off',) if c=='reference' else ()):
   assert (seed,c,b) in branch_keys,(seed,c,b)
for rec in records['branches']:assert rec['checkpoint_sha256']==hash_by[int(rec['seed'])]
for name,data in records.items():
 with (o.out/(name+'.csv')).open('w',newline='',encoding='utf8') as f:
  writer=csv.DictWriter(f,list(data[0]));writer.writeheader();writer.writerows(data)
by={(int(r['seed']),r['scenario'],r['branch']):r for r in records['branches']}
metrics=('births_since_checkpoint','deaths_since_checkpoint','max_generation','root_carriers','root_uptake','regional_migration_events','blocked_crossings','body_architectures')
rows=[]
for c in conditions:
 for metric in metrics:
  deltas=[float(by[(seed,c,'prune_root')][metric])-float(by[(seed,c,'control')][metric]) for seed in seeds]
  rows.append({'scenario':c,'metric':metric,'mean_pruned_minus_control':statistics.fmean(deltas),
   'median_pruned_minus_control':statistics.median(deltas),'positive':sum(x>0 for x in deltas),
   'negative':sum(x<0 for x in deltas),'equal':sum(x==0 for x in deltas),
   'raw_paired_deltas':deltas})
summary={'status':'exploratory, not long-term evidence of open-ended innovation',
 'version':'10.11','seed_manifest':seeds,'checkpoint_tick':300,'horizon_tick':2200,
 'scenarios':list(conditions),'per_seed_branches':11,'branch_count':len(records['branches']),
 'trace_count':len(records['trajectories']),'paired_comparisons':rows,
 'methodology':['Each seed has a single source checkpoint file, shared among independent experimental trajectories.',
 'Normal and genotype-pruned individuals compete within each continuous simulated world, but separate intervention branches do not interact.',
 'Root pruning deletes dependent body structures; changes in births are compound perturbation effects, not unit-organ fitness.',
 'At/near population carrying capacity, birth events can be balanced by deaths.',
 'Only a six-seed exploratory sample; no proof of sustained adaptive advantage.',
 'Native checkpoint file hashes may differ across separately re-generated same-seed files; replay tests compare trajectories from the exact same file.']}
(o.out/'summary.json').write_text(json.dumps(summary,indent=2,ensure_ascii=False)+'\n',encoding='utf8')
with (o.out/'paired_summary.csv').open('w',newline='',encoding='utf8') as f:
 w=csv.DictWriter(f,fieldnames=['scenario','metric','mean_pruned_minus_control','median_pruned_minus_control','positive','negative','equal','raw_paired_deltas']);w.writeheader()
 for rec in rows:w.writerow({**rec,'raw_paired_deltas':json.dumps(rec['raw_paired_deltas'])})
print('VALIDATED',len(records['branches']),'branches',len(records['trajectories']),'trajectories',len(seeds),'seeds');print('Births paired prune-control:')
for row in rows:
 if row['metric']=='births_since_checkpoint':print(row['scenario'],round(row['mean_pruned_minus_control'],2),row['positive'],row['negative'],row['raw_paired_deltas'])
